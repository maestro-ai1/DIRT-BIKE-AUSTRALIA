// scripts/gen-image-variants.cjs
// Creates smaller WebP copies of large catalogue/hero images (public/images/_w/<width>/<path>.webp) and writes src/config/image-variants.ts,
// a lookup used by components to emit srcSet. Originals are never modified or moved. Re-run after adding images: node scripts/gen-image-variants.cjs
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const IMG = path.join(ROOT, 'public', 'images');
const OUT = path.join(IMG, '_w');
const EXT = /\.(jpe?g|png|webp|avif)$/i;

function walk(d, acc = []) {
  for (const n of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, n.name);
    if (n.isDirectory()) { if (n.name !== '_w') walk(p, acc); }
    else if (EXT.test(n.name)) acc.push(p);
  }
  return acc;
}

(async () => {
  const map = {};
  let made = 0, skipped = 0, bytesOrig = 0, bytesNew = 0;
  for (const file of walk(IMG)) {
    const rel = path.relative(IMG, file).split(path.sep).join('/');
    const isHero = /(^|\/)hero-/.test(rel);
    const target = isHero ? 960 : 600;
    let meta;
    try { meta = await sharp(file).metadata(); } catch { skipped++; continue; }
    if (!meta.width || meta.width < target * 1.25) { skipped++; continue; } // not worth a variant
    const out = path.join(OUT, String(target), rel.replace(EXT, '') + '.webp');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    if (!fs.existsSync(out)) {
      await sharp(file).resize({ width: target, withoutEnlargement: true }).webp({ quality: isHero ? 74 : 78 }).toFile(out);
      made++;
    }
    bytesOrig += fs.statSync(file).size;
    bytesNew += fs.statSync(out).size;
    map['/images/' + rel] = { v: `/images/_w/${target}/${rel.replace(EXT, '')}.webp`, vw: target, w: meta.width };
  }
  const body = '// Generated by scripts/gen-image-variants.cjs: original image path -> smaller WebP variant (used for srcSet). Do not hand-edit.\n' +
    'export const IMAGE_VARIANTS: Record<string, { v: string; vw: number; w: number }> = ' + JSON.stringify(map, null, 1) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'src', 'config', 'image-variants.ts'), body);
  console.log('variants', Object.keys(map).length, '| new files', made, '| skipped (small/unreadable)', skipped,
    '| originals', (bytesOrig / 1048576).toFixed(1) + ' MB -> variants', (bytesNew / 1048576).toFixed(1) + ' MB');
})();
